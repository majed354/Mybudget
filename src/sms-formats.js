/** بصمات تعرّف المصرف من نصّ الرسالة أو من اسم المرسِل. */
export const BANK_SIGNS = [
  { id: 'albilad', ar: 'بنك البلاد', text: /مشتريات انترنت|شراء نقاط بيع|حواله محليه صادره|امر مستديم حواله|رقم الحساب\s*[:：]?\s*xx/i, sender: /albilad|البلاد/i },
  { id: 'rajhi', ar: 'مصرف الراجحي', text: /فيزا-ابل باي|بطاقه فيزا\s*[:：]|شراء عبر نقاط البيع/i, sender: /rajhi|alrajhi|الراجحي/i },
  { id: 'stc', ar: 'stc bank', text: /سعر تحويل العملات|اجمالي المبلغ المستحق|الرصيد المتبقي/i, sender: /stc/i },
];

export function detectBank(text, sender = '') {
  for (const b of BANK_SIGNS) if (sender && b.sender.test(sender)) return b;
  for (const b of BANK_SIGNS) if (b.text.test(text)) return b;
  return null;
}

