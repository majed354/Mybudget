/**
 * التاريخ في رسائل هذه المصارف يأتي على وجوهٍ متناقضة، وبعضها ملتبس حقًّا:
 * الراجحي يكتب `2/8/26` (يوم/شهر/سنة) و`26/8/6` (سنة/شهر/يوم) في الرسالة
 * نفسها من المصرف نفسه. وstc يكتب `06-08-2026` بشرطات.
 *
 * فلا تكفي أنماطٌ مرتّبة: `26/8/6` لم يكن يطابق شيئًا (السنة محرفٌ واحد)،
 * و`06-08-2026` كذلك (الشرطات مع اليوم أولًا) — فيسقطان على تاريخ اليوم في
 * صمت، فتُقيَّد عملية السادس على الثامن. وذلك أخطر من رسالةٍ لا تُفهم:
 * تلك تُعرض للمراجعة، وهذه تدخل الحساب بتاريخٍ كاذب.
 *
 * فالحلّ أن تُستخرج الأعداد الثلاثة ثم يُرجَّح بينها بالقرب من تاريخ الرسالة:
 * إشعار البنك يصف حدثًا وقع قبل ساعات لا قبل عشرين سنة.
 */
export const DATE_RE = /(?:^|\n|\s|:)(\d{1,4})[-/.](\d{1,2})[-/.](\d{1,4})(?:\s+(\d{1,2}:\d{2}))?/;

const daysIn = (y, m) => new Date(Date.UTC(y, m, 0)).getUTCDate();
const iso = (y, m, d) =>
  (y >= 1990 && y <= 2100 && m >= 1 && m <= 12 && d >= 1 && d <= daysIn(y, m))
    ? `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}` : null;

/**
 * يرجّح بين قراءات الثلاثيّ بالأقرب إلى يوم الرسالة.
 * والأولوية عند تساوي البُعد: يوم/شهر/سنة أولًا فهي السائدة في كشوف المملكة،
 * ثم سنة/شهر/يوم، ثم شهر/يوم/سنة — ولا يُلجأ إلى الأخيرة إلا حين تستحيل
 * سابقتاها (٠٧/٢٨/٢٦ لا تقرأ إلا شهرًا أولًا، فلا شهر ثامنٌ وعشرون).
 */
export function resolveDate(a, b, c, today) {
  const cands = [];
  const add = (v, rank) => { if (v) cands.push({ v, rank }); };
  if (a >= 1000) add(iso(a, b, c), 0);                    // 2026-08-04
  if (c >= 1000) add(iso(c, b, a), 0);                    // 06-08-2026
  if (a < 100 && c < 100) {
    add(iso(2000 + c, b, a), 1);                          // 2/8/26  ⇒ يوم/شهر/سنة
    add(iso(2000 + a, b, c), 2);                          // 26/8/6  ⇒ سنة/شهر/يوم
    add(iso(2000 + c, a, b), 3);                          // 07/28/26 ⇒ شهر/يوم/سنة
  }
  if (!cands.length) return null;
  const t = Date.parse(`${today}T00:00:00Z`);
  cands.sort((x, y) => {
    const d = Math.abs(Date.parse(x.v) - t) - Math.abs(Date.parse(y.v) - t);
    return d !== 0 ? d : x.rank - y.rank;
  });
  return cands[0].v;
}

