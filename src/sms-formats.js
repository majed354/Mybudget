/**
 * توحيد الرسم قبل المطابقة: الياء والألف والتاء المربوطة تُكتب على وجوه.
 * الاستبدال حرفٌ بحرف عمدًا، فتبقى المواضع متطابقة مع النصّ الأصلي
 * ونستطيع أن نطابق على المُوحَّد ثم نقتطع الاسم من الأصل كما كتبه البنك.
 */
export function foldArabic(s) {
  return String(s || '')
    .replace(/ى/g, 'ي')
    .replace(/[إأآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ـ/g, ' ');
}

